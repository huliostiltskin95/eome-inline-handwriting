import esbuild from "esbuild";
import process from "process";
import { readFileSync } from "fs";

const thirdPartyNotices = readFileSync(new URL("./THIRD_PARTY_NOTICES.md", import.meta.url), "utf8");

const banner =
`/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
/*
${thirdPartyNotices}
*/
`;

const prod = (process.argv[2] === "production");

const context = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: ["src/main.ts"],
	bundle: true,
	external: [
		"obsidian",
		"electron",
		"@codemirror/autocomplete",
		"@codemirror/collab",
		"@codemirror/commands",
		"@codemirror/language",
		"@codemirror/lint",
		"@codemirror/search",
		"@codemirror/state",
		"@codemirror/view",
		"@lezer/common",
		"@lezer/highlight",
		"@lezer/lr"],
	format: "cjs",
	platform: "browser",
	target: "es2018",
	logLevel: "info",
	// This workspace is also the live, iCloud-synced Obsidian plugin folder.
	// Inline maps make every development rebuild several times larger and make
	// Obsidian parse the map as part of the plugin. The unminified development
	// bundle remains readable without embedding that payload.
	sourcemap: false,
	treeShaking: true,
	outfile: "main.js",
	minify: prod,
	legalComments: "eof",
});

if (prod) {
	await context.rebuild();
	process.exit(0);
} else {
	await context.watch();
}
